class User(TimestampMixin, Base):
    """
    A StayVise user — onboarded via verified email and phone number.
    Password is nullable because auth is secure-link first; password may be
    set later for dashboard access.
    """

    __tablename__ = "users"
    __table_args__ = (
        Index(
            "uq_razorpay_fund_account",
            "razorpay_fund_account_id",
            unique=True,
            postgresql_where=text("razorpay_fund_account_id IS NOT NULL"),
        ),
    )

    id: Mapped[str] = mapped_column(
        GUID(),
        primary_key=True,
        default=lambda: str(__import__('uuid').uuid4()),
    )
    unique_id: Mapped[str] = mapped_column(
        String(20),
        unique=True,
        nullable=False,
        index=True,
        default=lambda: f"SV-{__import__('secrets').token_hex(4).upper()}",
        comment="Short unique ID for admins and user profiles (e.g. SV-1A2B3C4D)",
    )
    phone_number: Mapped[Optional[str]] = mapped_column(
        String(20),
        unique=True,
        nullable=True,
        index=True,
        comment="E.164 format, e.g. +919876543210. Null for magic link users until verified.",
    )
    messenger_name: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
        comment="Profile name from the messaging platform (Meta)",
    )
    full_name: Mapped[str] = mapped_column(String(255), nullable=False)
    email: Mapped[Optional[str]] = mapped_column(
        String(255), unique=True, nullable=True, index=True
    )
    username: Mapped[Optional[str]] = mapped_column(
        String(50),
        unique=True,
        nullable=True,
        index=True,
        comment="Public vanity URL slug, e.g. stayvise.in/p/username",
    )
    bio: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        comment="Short biography / What I do (Markdown supported)",
    )
    avatar_url: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        comment="Profile photo URL or local data URI for dashboard/public profile",
    )
    password_hash: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
        comment="bcrypt hash; NULL for OTP-only users",
    )
    role: Mapped[UserRole] = mapped_column(
        SAEnum(UserRole, native_enum=False, length=20),
        nullable=False,
        default=UserRole.freelancer,
    )
    is_verified: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("true")
    )
    onboarding_complete: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )

    # ── Preferences & Billing ─────────────────────────────────────────────────
    notification_prefs: Mapped[dict] = mapped_column(
        JSONType(),
        nullable=False,
        server_default=text("'{}'::jsonb"),
        comment="JSON record of notification toggles",
    )
    billing_plan: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        server_default=text("'free'"),
        comment="'free' or 'pro'",
    )
    payout_details: Mapped[dict] = mapped_column(
        JSONType(),
        nullable=False,
        server_default=text("'{}'::jsonb"),
        comment="Masked payout configuration shown in dashboard settings",
    )
    subscription_expires_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # ── Razorpay (for payouts) ────────────────────────────────────────────────
    razorpay_contact_id: Mapped[Optional[str]] = mapped_column(
        String(100), nullable=True,
        comment="RazorpayX Contact ID for this user",
    )
    razorpay_fund_account_id: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
        comment="RazorpayX Fund Account ID (bank/UPI) for payouts",
    )
    razorpay_subscription_id: Mapped[Optional[str]] = mapped_column(
        String(100), nullable=True,
        comment="Razorpay Subscription ID for Pro plan billing",
    )

    # ── Sensitive Data (Encrypted) ──────────────────────────────────────────
    _bank_account_number: Mapped[Optional[str]] = mapped_column(
        "bank_account_number", Text, nullable=True
    )

    @property
    def bank_account_number(self) -> Optional[str]:
        if not self._bank_account_number:
            return None
        return _get_fernet().decrypt(self._bank_account_number.encode()).decode()

    @bank_account_number.setter
    def bank_account_number(self, value: str) -> None:
        self._bank_account_number = _get_fernet().encrypt(value.encode()).decode()

    # ── Relationships ──────────────────────────────────────────────────────────
    trust_score: Mapped[Optional["TrustScore"]] = relationship(
        "TrustScore", back_populates="user", uselist=False, lazy="selectin", cascade="all, delete-orphan", passive_deletes=True
    )
    freelancer_projects: Mapped[list["Project"]] = relationship(
        "Project",
        foreign_keys="Project.freelancer_id",
        back_populates="freelancer",
        lazy="selectin",
    )
    client_projects: Mapped[list["Project"]] = relationship(
        "Project",
        foreign_keys="Project.client_id",
        back_populates="client",
        lazy="selectin",
    )
    raised_disputes: Mapped[list["Dispute"]] = relationship(
        "Dispute",
        foreign_keys="Dispute.raised_by_id",
        back_populates="raised_by",
        lazy="selectin",
    )
    resolved_disputes: Mapped[list["Dispute"]] = relationship(
        "Dispute",
        foreign_keys="Dispute.resolved_by_id",
        back_populates="resolved_by",
        lazy="selectin",
    )
    notifications: Mapped[list["Notification"]] = relationship(
        "Notification", back_populates="user", lazy="selectin", cascade="all, delete-orphan", passive_deletes=True
    )
    app_sessions: Mapped[list["UserSession"]] = relationship(
        "UserSession", back_populates="user", lazy="selectin", cascade="all, delete-orphan", passive_deletes=True
    )

    @property
    def active_sessions_count(self) -> int:
        return sum(1 for s in self.app_sessions if s.is_active)

    def __repr__(self) -> str:
        return (
            f"<User id={self.id!r} phone={self.phone_number!r} "
            f"role={self.role.value!r}>"
        )


