class Milestone(TimestampMixin, Base):
    """
    A deliverable unit within a project.

    Invariant (service layer):
        project.total_amount == SUM(milestone.amount for milestone in project.milestones)

    sequence_number is 1-indexed and determines the order milestones must be
    completed in (sequential release model).
    """

    __tablename__ = "milestones"
    __table_args__ = (
        # Unique ordering within a project
        UniqueConstraint("project_id", "sequence_number", name="uq_milestone_project_seq"),
        # Fast sorted fetch of milestones for a project
        Index("ix_milestones_project_sequence", "project_id", "sequence_number"),
        CheckConstraint("amount > 0", name="chk_positive_milestone"),
        CheckConstraint("sequence_number > 0", name="chk_seq_positive"),
        Index(
            "idx_pending_auto_release",
            "auto_release_at",
            postgresql_where=text("status = 'submitted'"),
        ),
    )

    id: Mapped[str] = mapped_column(
        GUID(),
        primary_key=True,
        default=lambda: str(__import__('uuid').uuid4()),
    )
    project_id: Mapped[str] = mapped_column(
        GUID(),
        ForeignKey("projects.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    amount: Mapped[int] = mapped_column(sa.BigInteger, nullable=False, comment="In paise")
    sequence_number: Mapped[int] = mapped_column(Integer, nullable=False)

    status: Mapped[MilestoneStatus] = mapped_column(
        SAEnum(MilestoneStatus, native_enum=False, length=20),
        nullable=False,
        default=MilestoneStatus.pending,
        index=True,
    )

    submitted_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    approved_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    released_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    auto_release_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="Funds release automatically after N days if client silent",
    )
    razorpay_payout_id: Mapped[Optional[str]] = mapped_column(
        String(100), nullable=True, comment="Razorpay Payout ID after funds released"
    )

    # ── Relationships ──────────────────────────────────────────────────────────
    project: Mapped["Project"] = relationship(
        "Project", back_populates="milestones", lazy="selectin"
    )
    disputes: Mapped[list["Dispute"]] = relationship(
        "Dispute", back_populates="milestone", lazy="selectin"
    )
    transactions: Mapped[list["Transaction"]] = relationship(
        "Transaction", back_populates="milestone", lazy="selectin"
    )

    def __repr__(self) -> str:
        return (
            f"<Milestone id={self.id!r} seq={self.sequence_number} "
            f"title={self.title!r} status={self.status.value!r} amount={self.amount}>"
        )


