class Project(TimestampMixin, Base):
    """
    An escrow project between one freelancer and one client.

    Financial invariant (enforced in service layer):
        total_amount == sum(milestones.amount)
        platform_fee_amount == total_amount * settings.ESCROW_FEE_PERCENT / 100
        freelancer_payout_amount == total_amount - platform_fee_amount
    """

    __tablename__ = "projects"
    __table_args__ = (
        # Fast lookup: all projects for a freelancer filtered by status
        Index("ix_projects_freelancer_status", "freelancer_id", "status"),
        # Fast lookup: all projects for a client filtered by status
        Index("ix_projects_client_status", "client_id", "status"),
        CheckConstraint(
            "total_amount > 0",
            name="chk_positive_amount",
        ),
        CheckConstraint(
            "platform_fee_amount >= 0",
            name="ck_projects_non_negative_fee",
        ),
        CheckConstraint(
            "freelancer_id != client_id",
            name="chk_no_self_deal",
        ),
        CheckConstraint(
            "deadline IS NULL OR deadline > (created_at AT TIME ZONE 'UTC')::date",
            name="chk_deadline_future",
        ),
        Index(
            "idx_projects_active",
            "freelancer_id",
            "updated_at",
            postgresql_where=text("status NOT IN ('completed', 'cancelled')"),
        ),
    )

    id: Mapped[str] = mapped_column(
        GUID(),
        primary_key=True,
        default=lambda: str(__import__('uuid').uuid4()),
    )
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)

    freelancer_id: Mapped[Optional[str]] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=True,
    )
    client_id: Mapped[str] = mapped_column(
        GUID(),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
    )

    status: Mapped[ProjectStatus] = mapped_column(
        SAEnum(ProjectStatus, native_enum=False, length=30),
        nullable=False,
        default=ProjectStatus.draft,
        index=True,
    )
    is_public: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )

    total_amount: Mapped[int] = mapped_column(
        sa.BigInteger, nullable=False, comment="In paise."
    )
    platform_fee_amount: Mapped[int] = mapped_column(sa.BigInteger, nullable=False)
    freelancer_payout_amount: Mapped[int] = mapped_column(sa.BigInteger, nullable=False)
    currency: Mapped[str] = mapped_column(
        String(3), nullable=False, server_default=text("'INR'")
    )

    razorpay_order_id: Mapped[Optional[str]] = mapped_column(
        String(100), unique=True, nullable=True, index=True
    )
    razorpay_payment_id: Mapped[Optional[str]] = mapped_column(
        String(100), nullable=True
    )
    escrow_held_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    deadline: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    auto_release_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="Set when last milestone submitted; funds release if client silent",
    )

    # ── Relationships ──────────────────────────────────────────────────────────
    freelancer: Mapped["User"] = relationship(
        "User", foreign_keys=[freelancer_id], back_populates="freelancer_projects", lazy="selectin"
    )
    client: Mapped["User"] = relationship(
        "User", foreign_keys=[client_id], back_populates="client_projects", lazy="selectin"
    )
    milestones: Mapped[list["Milestone"]] = relationship(
        "Milestone",
        back_populates="project",
        cascade="all, delete-orphan",
        order_by="Milestone.sequence_number",
        lazy="selectin",
    )
    disputes: Mapped[list["Dispute"]] = relationship(
        "Dispute", back_populates="project", lazy="selectin"
    )
    transactions: Mapped[list["Transaction"]] = relationship(
        "Transaction", back_populates="project", lazy="selectin"
    )
    proposals: Mapped[list["Proposal"]] = relationship(
        "Proposal", back_populates="project", cascade="all, delete-orphan", lazy="selectin"
    )

    def __repr__(self) -> str:
        return (
            f"<Project id={self.id!r} title={self.title!r} "
            f"status={self.status.value!r} amount={self.total_amount}>"
        )


