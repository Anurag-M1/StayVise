# ══════════════════════════════════════════════════════════════════════════════
# Helper: SA Enum factory
# ══════════════════════════════════════════════════════════════════════════════


def _sa_enum(enum_class: type[enum.Enum], **kwargs) -> "SAEnum":  # type: ignore[name-defined]
    """Create a SQLAlchemy Enum that stores values as VARCHAR (not native PG enum)."""
    from sqlalchemy import Enum as SAEnum  # local import to avoid circular at module level
    return SAEnum(
        enum_class,
        native_enum=False,
        length=64,
        **kwargs,
    )


