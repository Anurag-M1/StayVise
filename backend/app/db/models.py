class Transaction(Base):
    """
    Immutable financial ledger. Records every money movement.
    No updated_at — transactions are append-only.

    metadata (JSONB) stores provider-specific raw response payloads
    (Razorpay order, payment, payout objects) for audit purposes.
    """

    __tablename__ = "transactions"
    __table_args__ = (
        Index("ix_transactions_project_type", "project_id", "transaction_type"),
        Index("ix_transactions_razorpay_ref", "razorpay_reference"),
        CheckConstraint("amount > 0", name="chk_positive_tx"),
    )

    id: Mapped[str] = mapped_column(
        GUID(),
        primary_key=True,
        default=lambda: str(__import__('uuid').uuid4()),
    )
    project_id: Mapped[Optional[str]] = mapped_column(
        GUID(),
        ForeignKey("projects.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    milestone_id: Mapped[Optional[str]] = mapped_column(
        GUID(),
        ForeignKey("milestones.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    transaction_type: Mapped[TransactionType] = mapped_column(
        SAEnum(TransactionType, native_enum=False, length=30),
        nullable=False,
        index=True,
    )
    amount: Mapped[int] = mapped_column(
        sa.BigInteger, nullable=False, comment="Always positive; direction from type; in paise"
    )
    razorpay_reference: Mapped[Optional[str]] = mapped_column(
        String(100), nullable=True
    )
    status: Mapped[TransactionStatus] = mapped_column(
        SAEnum(TransactionStatus, native_enum=False, length=20),
        nullable=False,
        default=TransactionStatus.pending,
        index=True,
    )
    tx_metadata: Mapped[dict] = mapped_column(
        JSONType(),
        nullable=False,
        default=dict,
        comment="Raw Razorpay response + any extra context",
    )
    previous_audit_hash: Mapped[Optional[str]] = mapped_column(
        String(64),
        nullable=True,
        comment="Hash of the previous transaction in this project's audit chain",
    )
    audit_hash: Mapped[Optional[str]] = mapped_column(
        String(64),
        nullable=True,
        index=True,
        comment="SHA-256 digest for append-only transaction verification",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    # ── Relationships ──────────────────────────────────────────────────────────
    project: Mapped["Project"] = relationship(
        "Project", back_populates="transactions", lazy="selectin"
    )
    milestone: Mapped[Optional["Milestone"]] = relationship(
        "Milestone", back_populates="transactions", lazy="selectin"
    )

    def __repr__(self) -> str:
        return (
            f"<Transaction id={self.id!r} type={self.transaction_type.value!r} "
            f"amount={self.amount} status={self.status.value!r}>"
        )


