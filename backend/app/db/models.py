from __future__ import annotations
"""
StayVise — SQLAlchemy ORM Models
=================================
Tables
------
  users               Phone-first users (freelancers & clients)
  projects            Escrow projects linking a freelancer ↔ client
  milestones          Deliverable chunks inside a project
  trust_scores        Rolling trust metric per user (1-to-1 with users)
  disputes            Conflict records tied to a project/milestone
  transactions        Immutable financial ledger entries
  notifications       Outbound message log (email / push)

Design notes
------------
- All PKs: UUID generated by Postgres (gen_random_uuid())
- Timestamps: server-side via func.now(); updated_at uses onupdate
- Enums: Python Enum + SQLAlchemy Enum(native_enum=False) → stored as VARCHAR
- JSONB / ARRAY: backend-specific types (PostgreSQL only)
- Relationships: lazy="selectin" so async code never hits lazy-load errors
- Milestone sum == project total_amount is enforced in the service layer
  (cannot be done as a pure DB CHECK without a subquery, which is DDL-version-
  specific; a DB trigger is an alternative documented in infra/postgres/triggers.sql)
"""


